-- Synthetic retail schema. Demo data only: no real company data.
-- Re-runnable: drops and recreates every table.

DROP TABLE IF EXISTS inventory, order_items, orders, customers, stores, products, categories CASCADE;

CREATE TABLE categories (
    category_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    description  text
);

CREATE TABLE products (
    product_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text NOT NULL UNIQUE,
    name         text NOT NULL,
    category_id  integer NOT NULL REFERENCES categories (category_id),
    brand        text NOT NULL,
    unit_price   numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    unit_cost    numeric(10, 2) NOT NULL CHECK (unit_cost >= 0),
    is_active    boolean NOT NULL DEFAULT true,
    created_at   date NOT NULL
);

CREATE TABLE stores (
    store_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    store_type   text NOT NULL CHECK (store_type IN ('physical', 'online')),
    city         text,
    region       text,
    opened_on    date NOT NULL,
    CHECK (store_type = 'online' OR (city IS NOT NULL AND region IS NOT NULL))
);

CREATE TABLE customers (
    customer_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   text NOT NULL,
    last_name    text NOT NULL,
    email        text NOT NULL UNIQUE,
    city         text NOT NULL,
    region       text NOT NULL,
    birth_date   date NOT NULL,
    signup_date  date NOT NULL,
    loyalty_tier text NOT NULL CHECK (loyalty_tier IN ('bronze', 'silver', 'gold', 'platinum'))
);

CREATE TABLE orders (
    order_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    integer NOT NULL REFERENCES customers (customer_id),
    store_id       integer NOT NULL REFERENCES stores (store_id),
    order_date     timestamp NOT NULL,
    shipped_date   date,
    status         text NOT NULL CHECK (status IN ('pending', 'completed', 'cancelled', 'returned')),
    payment_method text NOT NULL CHECK (payment_method IN ('card', 'cash', 'paypal', 'gift_card')),
    CHECK (shipped_date IS NULL OR shipped_date >= order_date::date)
);

CREATE TABLE order_items (
    order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      integer NOT NULL REFERENCES orders (order_id),
    product_id    integer NOT NULL REFERENCES products (product_id),
    quantity      integer NOT NULL CHECK (quantity > 0),
    unit_price    numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    discount      numeric(4, 3) NOT NULL DEFAULT 0 CHECK (discount >= 0 AND discount <= 0.5),
    UNIQUE (order_id, product_id)
);

CREATE TABLE inventory (
    store_id         integer NOT NULL REFERENCES stores (store_id),
    product_id       integer NOT NULL REFERENCES products (product_id),
    quantity_on_hand integer NOT NULL CHECK (quantity_on_hand >= 0),
    reorder_level    integer NOT NULL CHECK (reorder_level >= 0),
    last_restocked   date NOT NULL,
    PRIMARY KEY (store_id, product_id)
);

-- Indexes on foreign keys and common filters (Postgres does not index FKs automatically).
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_store ON orders (store_id);
CREATE INDEX idx_orders_order_date ON orders (order_date);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);
CREATE INDEX idx_inventory_product ON inventory (product_id);

