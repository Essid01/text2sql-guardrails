"""Export answers marked incorrect as candidate evaluation cases.

    python -m text2sql.feedback --out evals/feedback_candidates.yaml

The file is a review queue, not test data: a human checks each case, writes or fixes the
expected SQL, then moves it into the evaluation set (Phase 5). Nothing is added to the
evaluation set automatically, so no unverified "gold" SQL can sneak in.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

from text2sql.history import HistoryEntry, HistoryStore


def to_candidates(entries: list[HistoryEntry]) -> list[dict[str, Any]]:
    """One review item per incorrect answer, oldest first."""
    candidates = []
    for e in entries:
        assert e.feedback is not None  # noqa: S101  # only entries with feedback are passed
        candidates.append({
            "id": f"feedback-{e.query_id}",
            "question": e.question,
            "status": "to_review",
            "answered_status": e.status,
            "sql_generated": e.sql_generated,
            "sql_executed": e.sql_executed,
            "confidence": e.confidence,
            "likely_hallucination": e.likely_hallucination,
            "user_comment": e.feedback.comment,
            "user_corrected_sql": e.feedback.corrected_sql,
            "reported_at": e.feedback.created_at.isoformat(),
        })  # fmt: skip
    return candidates


def export(store: HistoryStore, out: Path) -> int:
    """Write the candidates to `out` (YAML) and return how many were written."""
    candidates = to_candidates(store.incorrect())
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `python -m text2sql.feedback`. Review before use: see module doc.\n"
    body = yaml.safe_dump(candidates, allow_unicode=True, sort_keys=False, width=100)
    out.write_text(header + body, encoding="utf-8")
    return len(candidates)


def main() -> None:
    from text2sql.config import get_settings
    from text2sql.history import PostgresHistoryStore

    parser = argparse.ArgumentParser(description="Export incorrect answers for review.")
    parser.add_argument("--out", type=Path, default=Path("evals/feedback_candidates.yaml"))
    args = parser.parse_args()
    count = export(PostgresHistoryStore(get_settings().database_url), args.out)
    print(f"{count} incorrect answer(s) written to {args.out}")


if __name__ == "__main__":
    main()
